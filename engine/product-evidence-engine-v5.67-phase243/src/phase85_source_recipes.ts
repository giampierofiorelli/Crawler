/** Only exact product-model match is accepted; price/availability never implies discontinuation. */
export function extractBySourceRecipe(input:{recipe:SourceExtractionRecipe;html:string;
 pageUrl:string;expectedModel:string;}):RecipeExtraction{
 const out:RecipeExtraction={status:'blocked',reasons:[],facts:[],sourceSha256:null,
  storedSourceHtml:false,rankingEligible:false,publicationReady:false};
 const {recipe,html,pageUrl,expectedModel}=input;
 try{
  validateRecipe(recipe);
  if(!text(expectedModel,120)||!text(pageUrl,1500))throw Error('Invalid expected model or URL');
  const url=new URL(pageUrl);
  if(url.protocol!=='https:'||url.hostname!==recipe.host||!url.pathname.startsWith(recipe.pathPrefix)||
     (url.port&&url.port!=='443')||url.username||url.password)throw Error('Recipe does not match source path');
  const blocks=jsonLdBlocks(html);
  const products:Record<string,unknown>[]=blocks.flatMap(b=>objects(b.data).filter(obj=>productType(obj['@type'])).map(obj=>({...obj,_source:b.source}))); 
  // Deliberately fail-closed on aggregate pages: do not mix facts from sibling variants.
  if(products.length!==1)throw Error('Expected precisely one Product in JSON-LD');
  const p=products[0];
  if(p.model!==expectedModel)throw Error('Product model identity not confirmed');
  const props=p.additionalProperty;
  if(!Array.isArray(props)||props.length>100)throw Error('No bounded Product additionalProperty');
  const slices=originalObjectSlices(p._source as string);
  for(const mapping of recipe.mappings){
   const matching=props.filter((q:unknown)=>!!q&&typeof q==='object'&&!Array.isArray(q)&&
    (q as Record<string,unknown>).name===mapping.propertyName) as Record<string,unknown>[];
   if(matching.length!==1)continue;
   const prop=matching[0];
   if(prop['@type']!=='PropertyValue'&&prop['@type']!=='https://schema.org/PropertyValue')continue;
   if(prop.unitCode===undefined&&prop.unitText===undefined)continue;
   if(prop.unitCode!==undefined&&prop.unitCode!==mapping.unit)continue;
   if(prop.unitText!==undefined&&prop.unitText!==mapping.unit)continue;
   const value=prop.value;
   const literal=typeof value==='number'&&Number.isFinite(value)?String(value):
    typeof value==='string'&&/^-?(?:0|[1-9]\d*)(?:\.\d+)?$/.test(value)?value:null;
   if(!literal||!Number.isFinite(Number(literal))||Math.abs(Number(literal))>1_000_000_000)continue;
   // Identical JSON property object must occur once as raw source text. No fuzzy matching.
   const validSlices=slices.filter(s=>{
    try{const o=JSON.parse(s);return o.name===mapping.propertyName&&o.value===value&&
      (o['@type']==='PropertyValue'||o['@type']==='https://schema.org/PropertyValue');}
    catch{return false;}
   });
   if(validSlices.length!==1||!validSlices[0].includes(literal))continue;
   out.facts.push({fieldKey:mapping.field.key,number:Number(literal),unit:mapping.unit,
    valueLiteral:literal,anchor:validSlices[0],sourceOrigin:'manufacturer_technical_specification'});
  }
  out.sourceSha256=sha(html);
  out.status=out.facts.length?'extracted_unverified':'blocked';
  if(!out.facts.length)out.reasons.push('no_exact_anchored_source_fields');
 }catch(e){out.reasons=[e instanceof Error?e.message:'unrecognized_recipe_error'];out.facts=[];}
 return out;
}
/** Creates an adapter for the EXISTING rights-checked Phase 72 matrix quarantine path.
 * Never call this adapter on an unapproved web body and never treat it as independent evidence. */
export function reviewedRecipeLocalAdapter(recipe:SourceExtractionRecipe,input:{pageUrl:string;
 expectedModel:string}):LocalSemanticAdapter {
 validateRecipe(recipe);
 if(recipe.status!=='reviewed')throw Error('AI proposal cannot be used as reviewed recipe');
 return {execution:'local_only',suggestTransient:(body)=>{
  const result=extractBySourceRecipe({recipe,html:body,...input});
  if(result.status!=='extracted_unverified')return [];
  return result.facts.map((fact,i):EphemeralSemanticSuggestion=>{
   const mapping=recipe.mappings.find(x=>x.field.key===fact.fieldKey)!;
   return {id:`obs_recipe_${i+1}`,definition:{kind:'field',field:mapping.field},
    origin:'manufacturer_technical_specification',value:{type:'number',number:fact.number,unit:fact.unit},
    context:mapping.context,protocolId:null,protocolVersion:null,anchorText:fact.anchor,
    literalText:fact.valueLiteral,interpretation:'direct_source_value'};
  });
 }};
}
/** Evaluation of a PROPOSED recipe on independently labeled source pages. No automatic promotion. */
export function qualifyProposedRecipe(recipe:SourceExtractionRecipe,samples:readonly RecipeSample[]):RecipeQualification{
 validateRecipe(recipe);
 if(recipe.status!=='proposed'||!Array.isArray(samples)||samples.length>20)throw Error('Only bounded proposed recipes are evaluated');
 const failures:string[]=[];const keys=new Set<string>();let matchedFacts=0;
 for(const sample of samples){
  if(!id(sample.productKey)||keys.has(sample.productKey)||!text(sample.expectedModel,120)||
    !sample.expected||Object.keys(sample.expected).length!==recipe.mappings.length){failures.push('invalid_or_duplicate_labeled_sample');continue;}
  keys.add(sample.productKey);
  const result=extractBySourceRecipe({recipe,html:sample.html,
   pageUrl:`https://${recipe.host}${recipe.pathPrefix}${sample.productKey}`,expectedModel:sample.expectedModel});
  if(result.status!=='extracted_unverified'||result.facts.length!==recipe.mappings.length){failures.push(`${sample.productKey}:incomplete_extraction`);continue;}
  let correct=true;
  for(const m of recipe.mappings){
   const observed=result.facts.find(f=>f.fieldKey===m.field.key);
   if(!observed||!Number.isFinite(sample.expected[m.field.key])||observed.number!==sample.expected[m.field.key])correct=false;
   else matchedFacts++;
  }
  if(!correct)failures.push(`${sample.productKey}:field_value_mismatch`);
 }
 if(keys.size<2)failures.push('need_two_distinct_labeled_products');
 return {status:failures.length===0?'ready_for_human_review':'needs_revision',samples:samples.length,
  independentProductKeys:keys.size,matchedFacts,failures,noSourceHtmlStored:true};
}

