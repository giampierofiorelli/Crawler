function validateRecipe(r:SourceExtractionRecipe):void {
 if(!r||!id(r.recipeId)||!id(r.sourceId)||!id(r.categoryId)||!safeHost(r.host)||
   !/^\/[a-zA-Z0-9/_~-]{0,180}$/.test(r.pathPrefix)||!Number.isInteger(r.version)||r.version<1||r.version>100000||
   !['proposed','reviewed'].includes(r.status)||!Array.isArray(r.mappings)||r.mappings.length<1||r.mappings.length>20||
   (r.status==='reviewed'&&(!id(r.reviewedBy)||!text(r.reviewRef,160)))||
   (r.status==='proposed'&&(r.reviewedBy!==null||r.reviewRef!==null)))throw Error('Invalid recipe identity or review state');
 const names=new Set<string>(),fields=new Set<string>();
 for(const m of r.mappings){
  const f=m?.field;
  if(!f||!id(f.key)||!text(m.propertyName,80)||!text(m.unit,50)||!Object.is(f.type,'number')||
    f.unit!==m.unit||f.requiresProtocol||!Array.isArray(f.permittedOrigins)||
    f.permittedOrigins.length!==1||f.permittedOrigins[0]!=='manufacturer_technical_specification'||
    f.allowedValues.length!==0||!Array.isArray(f.contextKeys)||f.contextKeys.length<1||
    !m.context||Object.keys(m.context).length!==f.contextKeys.length||
    !f.contextKeys.every((k:string)=>id(k)&&id(m.context[k]))||
    names.has(m.propertyName.toLowerCase())||fields.has(f.key))throw Error('Invalid, duplicate or ambiguous recipe field');
  fields.add(f.key);names.add(m.propertyName.toLowerCase());
 }
}
/** No regex-based parsing of whole-page prose: only bounded, parseable JSON-LD Product data. */
function jsonLdBlocks(html:string):{source:string;data:unknown}[]{
 if(typeof html!=='string'||html.length>1_000_000||html.includes('\0'))throw Error('Invalid transient HTML');
 const out:{source:string;data:unknown}[]=[];
 const rx=/<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi;
 for(const m of html.matchAll(rx)){
  if(!/\btype\s*=\s*(?:["']application\/ld\+json["']|application\/ld\+json)(?:\s|$)/i.test(m[1]))continue;
  if(m[2].length>200000)throw Error('JSON-LD block too large');
  try{out.push({source:m[2],data:JSON.parse(m[2])});}
  catch{throw Error('Malformed JSON-LD — fail closed');}
  if(out.length>15)throw Error('Too many structured data blocks');
 }
 return out;
}
function objects(root:unknown):Record<string,unknown>[] {
 const found:Record<string,unknown>[]=[];
 const seen=new Set<unknown>();
 const visit=(x:unknown,depth:number)=>{
  if(depth>8||seen.size>2000)throw Error('Unbounded JSON-LD graph');
  if(!x||typeof x!=='object'||seen.has(x))return;
  seen.add(x);
  if(Array.isArray(x)){if(x.length>200)throw Error('Oversized JSON-LD list');for(const child of x)visit(child,depth+1);return;}
  const obj=x as Record<string,unknown>;found.push(obj);
  for(const [key,v] of Object.entries(obj))if(key!=='@context')visit(v,depth+1);
 };
 visit(root,0);return found;
}
function productType(v:unknown):boolean {return v==='Product'||Array.isArray(v)&&v.includes('Product')||v==='https://schema.org/Product';}
/** Find a contiguous original JSON object; used solely to bind an ephemeral literal to its original bytes. */
function originalObjectSlices(raw:string):string[]{
 const stack:number[]=[];const out:string[]=[];let inside=false,escape=false;
 for(let i=0;i<raw.length;i++){
  const c=raw[i];
  if(inside){if(escape)escape=false;else if(c==='\\')escape=true;else if(c==='"')inside=false;continue;}
  if(c==='"'){inside=true;continue;}
  if(c==='{')stack.push(i);
  else if(c==='}'&&stack.length){const start=stack.pop()!;const fragment=raw.slice(start,i+1);
   if(fragment.length<=300&&!/[<>\r\n]/.test(fragment))out.push(fragment);
  }
 }
 return out;
}
