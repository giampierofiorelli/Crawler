/**
 * Phase 66: selective, rights-gated user-experience research.
 * RESEARCH ONLY. No ranking updates, live crawling, Amazon reviews, price data,
 * retailer influence, claims of authenticity, or automated model calls.
 *
 * Sources of design (not validation): Value of Information (research prioritisation),
 * aspect-based sentiment analysis, review self-selection bias and UK CMA fake-review guidance.
 */
export type GapType =
  'long_term_use' | 'situational_experience' | 'ergonomic_experience' |
  'controlled_performance_measurement' | 'technical_compatibility' | 'unknown_need';
export type Coverage = 'sufficient_for_question' | 'partial' | 'missing';
export type SearchDecision =
  'no_search_sufficient_professional_evidence' |
  'clarify_user_need_first' |
  'professional_test_required' |
  'not_decision_material' |
  'rights_blocked' |
  'candidate_research_only';
export interface UnresolvedQuestion {
  id: string;
  productVariantId: string;
  criterionId: string;
  /** An actual user concern or a documented limitation of the current decision. */
  question: string;
  context: string | null;
  gapType: GapType;
  professionalCoverage: Coverage;
  /** Never generated by an LLM; explicit human/user or decision-audit provenance. */
  materialityBasis: 'user_explicit' | 'mandatory_user_requirement' | 'documented_robustness_gap' | 'not_established';
  materialityReference: string | null;
}
export interface ReviewSourceGrant {
  sourceId: string;
  host: string;
  approvedDocumentUrl: string;
  licenceValidUntil: string;
  approvalRecorded: boolean;
  automatedAcquisitionAllowed: boolean;
  commercialAnalysisAllowed: boolean;
  aiExtractionAllowed: boolean;
  /** A separate grant would be needed to transmit review text to a remote model. */
  remoteModelTransferAllowed: boolean;
  /** This is not authorization to publish original review text. */
  derivedObservationPublicationAllowed: boolean;
}
export type ReviewSearchPlan = {
  purpose: 'selective_supplemental_experience_research_only';
  questionId: string;
  status: SearchDecision;
  justifiedGap: string;
  sourceIds: string[];
  sourceHosts:Record<string,string>;
  permittedProcessing: 'none' | 'local_ai_candidate_extraction_only';
  resultInfluence: 'not_allowed_until_separate_human_and_legal_review';
  rationale: string[];
  cautions: string[];
};
const noCommerce = /(?:price|budget|cost|discount|deal|amazon|affiliate|retailer|merchant|commission|sponsored|advertis)/i;
const idOk = (x:unknown):x is string => typeof x==='string' && /^[a-z][a-z0-9_]{2,110}$/.test(x) && !noCommerce.test(x);
const refOk = (u:unknown):u is string=>{
  if(typeof u!=='string')return false;
  try {const p=new URL(u); return p.protocol==='https:'&&!p.username&&!p.password&&!!p.hostname&&!/(^|\.)amazon\./i.test(p.hostname);}catch{return false;}
};
const isoOk=(s:string):boolean => /^\d{4}-\d{2}-\d{2}$/.test(s)&& !Number.isNaN(Date.parse(s+'T00:00:00Z')) && new Date(s+'T00:00:00Z').toISOString().slice(0,10)===s;
const caution=[
  'Experiences are context-specific testimonies, not controlled measurements or population estimates.',
  'Source accessibility, declared approval and matching excerpts do not establish real identity, independence or licence validity.',
  'Do not derive a winner, probability, reliability coefficient or popularity statistic from these records.',
  'No Amazon customer reviews, retailer data, prices, or marketing claims are inputs.',
  'AI analysis may produce omissions or false interpretations; output remains quarantined for human checking.'
];
function validatedGrant(g:ReviewSourceGrant,asOf:string):boolean {
  if(!g||!idOk(g.sourceId)||!refOk(g.approvedDocumentUrl)||!isoOk(g.licenceValidUntil)||
     !g.approvalRecorded||!g.automatedAcquisitionAllowed||!g.commercialAnalysisAllowed||!g.aiExtractionAllowed)return false;
  const host=g.host.toLowerCase();
  if(!/^(?:[a-z0-9-]+\.)+[a-z]{2,}$/.test(host)||/(^|\.)amazon\./.test(host))return false;
  return g.licenceValidUntil>=asOf;
}
export function decideSelectiveUserReviewResearch(input:{
 question:UnresolvedQuestion;
 grants:readonly ReviewSourceGrant[];
 asOf:string;
}):ReviewSearchPlan {
 const {question:q,grants,asOf}=input;
 if(!q||!idOk(q.id)||!idOk(q.productVariantId)||!idOk(q.criterionId)||
    typeof q.question!=='string'||q.question.length<12||q.question.length>500||noCommerce.test(q.question)||
    (q.context!==null&&(typeof q.context!=='string'||q.context.length<4||q.context.length>500||noCommerce.test(q.context)))||
    !['long_term_use','situational_experience','ergonomic_experience','controlled_performance_measurement','technical_compatibility','unknown_need'].includes(q.gapType)||
    !['sufficient_for_question','partial','missing'].includes(q.professionalCoverage)||
    !['user_explicit','mandatory_user_requirement','documented_robustness_gap','not_established'].includes(q.materialityBasis)||
    !Array.isArray(grants)||grants.length>200||!isoOk(asOf))throw Error('Invalid selective research request');
 if(q.materialityBasis!=='not_established'&&(!q.materialityReference||q.materialityReference.trim().length<6))throw Error('Materiality needs an inspectable reference');
 const rationale:string[]=[];
 let status:SearchDecision;
 let sourceIds:string[]=[];
 let sourceHosts:Record<string,string>={};
 if(q.professionalCoverage==='sufficient_for_question'){
  status='no_search_sufficient_professional_evidence';rationale.push('The specified question already has adequate professional evidence; supplementary user reviews would not resolve an identified gap.');
 } else if(q.gapType==='unknown_need'||q.context===null){
  status='clarify_user_need_first';rationale.push('The relevant use context is not defined; ask a targeted clarification before collecting reviews.');
 } else if(q.gapType==='controlled_performance_measurement'||q.gapType==='technical_compatibility'){
  status='professional_test_required';rationale.push('User testimonials cannot replace controlled measurements or technical-compatibility verification.');
 } else if(q.materialityBasis==='not_established'){
  status='not_decision_material';rationale.push('No documented reason to expect these reviews to affect this user decision.');
 } else {
  const eligible=grants.filter(g=>validatedGrant(g,asOf));
  sourceIds=[...new Set(eligible.map(g=>g.sourceId))];
  if(sourceIds.length!==eligible.length || new Set(eligible.map(g=>g.host)).size!==eligible.length)throw Error('Ambiguous source grants');
  sourceHosts=Object.fromEntries(eligible.map(g=>[g.sourceId,g.host.toLowerCase()]));
  if(!sourceIds.length){status='rights_blocked';rationale.push('No documented, unexpired, scoped authorization for automated commercial AI analysis of these review sources.');}
  else {status='candidate_research_only';rationale.push(`Material ${q.gapType} question not resolved by professional tests; limited acquisition from sources with recorded approvals may be useful.`);}
 }
 return {
  purpose:'selective_supplemental_experience_research_only',questionId:q.id,status,justifiedGap:q.question,
  sourceIds,sourceHosts,permittedProcessing:status==='candidate_research_only'?'local_ai_candidate_extraction_only':'none',
  resultInfluence:'not_allowed_until_separate_human_and_legal_review',rationale,cautions:[...caution]
 };
}
/** A licensed input document. Use only if an independent rights/access gate has actually been passed. */
export interface ReviewTextRecord {
 reviewId:string;
 sourceId:string;
 productVariantId:string;
 sourceUrl:string;
 text:string;
 /** Documented incentive status; 'unknown' is NOT proof of authenticity. */
 incentive:'declared'|'not_reported'|'unknown';
}
/** An optional AI component proposes an excerpt-anchored candidate; it never publishes a conclusion. */
export interface AiObservationCandidate {
 reviewId:string;
 criterionId:string;
 claimedContext:string;
 claim:string;
 /** Exact source substring for a reviewer to check; never published automatically. */
 evidenceSpan:string;
 polarity:'positive'|'negative'|'mixed'|'descriptive';
}
export interface AiCandidateAudit {
 status:'quarantined_pending_human_review';
 sourceEvidenceAnchored:boolean;
 exactVariantMatched:boolean;
 matchingCriterion:boolean;
 contextNeedsHumanValidation:true;
 sourceIdentityVerified:false;
 legitimateUseAssuredBySoftware:false;
 canInfluenceRanking:false;
 issues:string[];
}
/** No call to an AI provider is made. Even a valid excerpt can be taken out of context. */
export function auditAiCandidate(input:{plan:ReviewSearchPlan;question:UnresolvedQuestion;record:ReviewTextRecord;candidate:AiObservationCandidate;}):AiCandidateAudit {
 const {plan,question:q,record:r,candidate:c}=input;
 if(!r||!c||typeof r.text!=='string'||r.text.length>20000||r.text.length<10||
    !idOk(r.reviewId)||!idOk(r.sourceId)||!idOk(r.productVariantId)||!refOk(r.sourceUrl)||
    !['declared','not_reported','unknown'].includes(r.incentive)||
    !idOk(c.reviewId)||!idOk(c.criterionId)||!['positive','negative','mixed','descriptive'].includes(c.polarity)||
    typeof c.claim!=='string'||c.claim.length<3||c.claim.length>600||
    typeof c.claimedContext!=='string'||c.claimedContext.length>500||
    typeof c.evidenceSpan!=='string'||c.evidenceSpan.length<10||c.evidenceSpan.length>500)throw Error('Invalid candidate evidence');
 const anchored=r.text.includes(c.evidenceSpan);
 const variant=r.productVariantId===q.productVariantId;
 const criterion=c.criterionId===q.criterionId;
 const issues:string[]=[];
 if(plan.status!=='candidate_research_only'||plan.questionId!==q.id||!plan.sourceIds.includes(r.sourceId)||
    new URL(r.sourceUrl).hostname.toLowerCase()!==plan.sourceHosts[r.sourceId])issues.push('no_permitted_selective_plan');
 if(!anchored)issues.push('candidate_not_anchored_in_source_text');
 if(!variant)issues.push('wrong_product_variant');
 if(!criterion)issues.push('different_criterion');
 if(r.incentive==='declared')issues.push('incentive_must_be_disclosed');
 if(r.incentive==='unknown')issues.push('incentive_status_unknown');
 issues.push('authenticity_bias_context_and_interpretation_need_external_validation');
 return {status:'quarantined_pending_human_review',sourceEvidenceAnchored:anchored,exactVariantMatched:variant,
  matchingCriterion:criterion,contextNeedsHumanValidation:true,sourceIdentityVerified:false,
  legitimateUseAssuredBySoftware:false,canInfluenceRanking:false,issues};
}
/** Growth is a reviewed research backlog, NOT self-modifying algorithmic weights. */
export function proposeTaxonomyResearch(input:{
 auditedPlans:readonly ReviewSearchPlan[];
 knownCriterionIds:readonly string[];
 hypotheses:readonly {questionId:string;candidateCriterionId:string}[];
}):{
 status:'human_approval_required';proposed:string[];rankingWeightsModified:false;publishedClaimsModified:false;
} {
 if(!Array.isArray(input.auditedPlans)||!Array.isArray(input.knownCriterionIds)||!Array.isArray(input.hypotheses)||
 input.auditedPlans.length>10000||input.hypotheses.length>1000)throw Error('Invalid research backlog');
 const known=new Set(input.knownCriterionIds);
 if([...known,...input.hypotheses.map(h=>h.candidateCriterionId)].some(x=>!idOk(x))||
    input.hypotheses.some(h=>!idOk(h.questionId)))throw Error('Invalid criterion or question ID');
 const grounded=new Set(input.auditedPlans.filter(p=>['candidate_research_only','rights_blocked'].includes(p.status)).map(p=>p.questionId));
 const proposed=[...new Set(input.hypotheses.filter(h=>grounded.has(h.questionId)).map(h=>h.candidateCriterionId))].filter(x=>!known.has(x)).sort();
 return {status:'human_approval_required',proposed,rankingWeightsModified:false,publishedClaimsModified:false};
}
